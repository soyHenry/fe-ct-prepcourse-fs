// Recuerda que debes utilizar el objeto global "Math".

function elevar(num, exponent) {
  // La funcion recibe dos argumentos llamados "num" y "exponent" los cuales son numeros.
  // Debes retorna el valor de "num" elevado al "exponent".
  // Tu codigo:
  return Math.pow(num, exponent);
}

module.exports = elevar;
